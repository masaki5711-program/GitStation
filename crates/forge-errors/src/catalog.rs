//! Catalog types shared by the generated table, `forge explain`, and the
//! catalog generator.

use crate::ErrorCode;

/// How urgently a code needs attention in production.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Severity {
    /// Pages / needs a runbook.
    Alert,
    /// Degraded but served; watch trends.
    Warn,
    /// Expected client-side condition.
    Info,
}

impl Severity {
    pub fn as_str(self) -> &'static str {
        match self {
            Severity::Alert => "alert",
            Severity::Warn => "warn",
            Severity::Info => "info",
        }
    }
}

/// Language for user-facing messages.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Ja,
    En,
}

/// One registry row, as generated from `errors.toml`.
#[derive(Debug)]
pub struct CatalogEntry {
    pub code: ErrorCode,
    pub id: &'static str,
    pub http_status: u16,
    pub severity: Severity,
    pub user_message_ja: &'static str,
    pub user_message_en: &'static str,
    pub cause: &'static str,
    pub diagnosis: &'static str,
    pub fix: &'static str,
    pub runbook: Option<&'static str>,
    pub test: &'static str,
    pub retired: bool,
}

impl CatalogEntry {
    pub fn user_message(&self, lang: Lang) -> &'static str {
        match lang {
            Lang::Ja => self.user_message_ja,
            Lang::En => self.user_message_en,
        }
    }

    /// The catalog page (`Git/docs/errors/<CODE>.md`), in Japanese prose
    /// headings so non-Claude readers can use it too.
    pub fn render_markdown(&self) -> String {
        let runbook = self.runbook.map_or_else(
            || "なし".to_string(),
            |r| format!("[`{r}`](../../ops/runbooks/{r}.md)"),
        );
        let retired = if self.retired {
            "\n> **廃止済み** — 新しいコードでは使わないこと。\n"
        } else {
            ""
        };
        format!(
            "<!-- @generated by `cargo run -p forge-errors --bin gen-catalog` from errors.toml — do not edit. -->\n\
             # {id}\n{retired}\n\
             | 項目 | 値 |\n|---|---|\n\
             | HTTP ステータス | {status} |\n| 重大度 | {sev} |\n| Runbook | {runbook} |\n| 発生させるテスト | `{test}` |\n\n\
             ## 利用者向けメッセージ\n\n- ja: {ja}\n- en: {en}\n\n\
             ## 原因 (cause)\n\n{cause}\n\n\
             ## 調べ方 (diagnosis)\n\n{diagnosis}\n\n\
             ## 対処 (fix)\n\n{fix}\n",
            id = self.id,
            status = self.http_status,
            sev = self.severity.as_str(),
            test = self.test,
            ja = self.user_message_ja,
            en = self.user_message_en,
            cause = self.cause,
            diagnosis = self.diagnosis,
            fix = self.fix,
        )
    }
}

/// Fallback used only if the generated table were ever inconsistent with the
/// enum (impossible by construction). It maps to the catch-all internal code
/// so the failure is still visible as an alert rather than a panic.
pub(crate) static MISSING_ENTRY: CatalogEntry = CatalogEntry {
    code: ErrorCode::Internal,
    id: "FG-SYS-0001",
    http_status: 500,
    severity: Severity::Alert,
    user_message_ja: "内部エラーが発生しました。",
    user_message_en: "An internal error occurred.",
    cause: "error catalog lookup failed (generated table inconsistent)",
    diagnosis: "rebuild forge-errors; check build.rs output",
    fix: "rebuild",
    runbook: Some("internal-error"),
    test: "every_code_round_trips_through_parse",
    retired: false,
};

/// Render the catalog index page (`Git/docs/errors/README.md`).
pub fn render_index(entries: &[&CatalogEntry]) -> String {
    let mut s = String::from(
        "<!-- @generated by `cargo run -p forge-errors --bin gen-catalog` from errors.toml — do not edit. -->\n\
         # エラーカタログ\n\n\
         すべての `FG-` エラーコードの一覧です。各ページに原因・調べ方・対処・Runbook があります。\n\n\
         | コード | HTTP | 重大度 | 原因 |\n|---|---|---|---|\n",
    );
    for e in entries {
        let first_sentence = e.cause.split(". ").next().unwrap_or(e.cause);
        s.push_str(&format!(
            "| [{id}]({id}.md){retired} | {status} | {sev} | {cause} |\n",
            id = e.id,
            retired = if e.retired { " (廃止)" } else { "" },
            status = e.http_status,
            sev = e.severity.as_str(),
            cause = first_sentence.replace('|', "\\|"),
        ));
    }
    s
}

/// Every catalog entry, for the generator and `forge errors list`.
pub fn entries() -> Vec<&'static CatalogEntry> {
    crate::CATALOG.iter().collect()
}
