//! Generates the `ErrorCode` enum and its catalog table from `errors.toml`.
//!
//! The registry is the single source of truth (CLAUDE.md §3.1). This build
//! script fails the build — with the offending code named — when an entry is
//! malformed, so a broken registry can never compile.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use serde::Deserialize;

#[derive(Deserialize)]
struct Registry {
    error: Vec<Entry>,
}

#[derive(Deserialize)]
struct Entry {
    code: String,
    name: String,
    http_status: u16,
    severity: String,
    user_message_ja: String,
    user_message_en: String,
    user_message_id: String,
    cause: String,
    diagnosis: String,
    fix: String,
    test: String,
    runbook: Option<String>,
    #[serde(default)]
    retired: bool,
}

const AREAS: [&str; 10] = [
    "AUTH", "GIT", "REPO", "DB", "CI", "DEPLOY", "DOC", "WEB", "SYS", "CLI",
];

fn main() {
    if let Err(msg) = run() {
        // build scripts report failure through a non-zero exit; the message is
        // what the developer (or Claude) sees in the cargo output.
        eprintln!("forge-errors build.rs: {msg}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    println!("cargo:rerun-if-changed=errors.toml");
    let text =
        fs::read_to_string("errors.toml").map_err(|e| format!("cannot read errors.toml: {e}"))?;
    let registry: Registry =
        toml::from_str(&text).map_err(|e| format!("errors.toml is not valid: {e}"))?;
    validate(&registry.error)?;

    let out_dir = env::var("OUT_DIR").map_err(|e| format!("OUT_DIR not set: {e}"))?;
    let out = PathBuf::from(out_dir).join("generated.rs");
    fs::write(&out, render(&registry.error))
        .map_err(|e| format!("cannot write {}: {e}", out.display()))
}

fn validate(entries: &[Entry]) -> Result<(), String> {
    let mut codes = BTreeSet::new();
    let mut names = BTreeSet::new();
    for e in entries {
        let parts: Vec<&str> = e.code.split('-').collect();
        let well_formed = parts.len() == 3
            && parts.first() == Some(&"FG")
            && parts.get(1).is_some_and(|a| AREAS.contains(a))
            && parts
                .get(2)
                .is_some_and(|n| n.len() == 4 && n.chars().all(|c| c.is_ascii_digit()));
        if !well_formed {
            return Err(format!(
                "{}: code must be FG-<AREA>-<NNNN> with AREA in {AREAS:?}",
                e.code
            ));
        }
        if !codes.insert(e.code.clone()) {
            return Err(format!("{}: duplicate code", e.code));
        }
        let pascal = e
            .name
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_uppercase())
            && e.name.chars().all(|c| c.is_ascii_alphanumeric());
        if !pascal || !names.insert(e.name.clone()) {
            return Err(format!(
                "{}: name '{}' must be a unique PascalCase identifier",
                e.code, e.name
            ));
        }
        if !(400..=599).contains(&e.http_status) {
            return Err(format!("{}: http_status must be 400-599", e.code));
        }
        if !matches!(e.severity.as_str(), "alert" | "warn" | "info") {
            return Err(format!("{}: severity must be alert|warn|info", e.code));
        }
        let prose = [
            &e.user_message_ja,
            &e.user_message_en,
            &e.user_message_id,
            &e.cause,
            &e.diagnosis,
            &e.fix,
            &e.test,
        ];
        if prose.iter().any(|s| s.trim().is_empty()) {
            return Err(format!(
                "{}: user messages, cause, diagnosis, fix and test must be non-empty",
                e.code
            ));
        }
        if e.severity == "alert"
            && !e.retired
            && e.runbook.as_deref().is_none_or(|r| r.trim().is_empty())
        {
            return Err(format!("{}: severity alert requires a runbook", e.code));
        }
    }
    Ok(())
}

fn severity_variant(s: &str) -> &'static str {
    match s {
        "alert" => "Severity::Alert",
        "warn" => "Severity::Warn",
        _ => "Severity::Info",
    }
}

fn render(entries: &[Entry]) -> String {
    let mut s =
        String::from("// @generated by forge-errors/build.rs from errors.toml — do not edit.\n\n");
    s.push_str("/// Every registered forge error code. Generated from `errors.toml`.\n");
    s.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum ErrorCode {\n");
    for e in entries {
        let _ = writeln!(s, "    /// `{}` — {}", e.code, e.cause.replace('\n', " "));
        if e.retired {
            s.push_str("    #[deprecated(note = \"retired error code\")]\n");
        }
        let _ = writeln!(s, "    {},", e.name);
    }
    s.push_str("}\n\n");

    s.push_str("/// Catalog entries in registry order.\n#[allow(deprecated)]\npub(crate) static CATALOG: &[CatalogEntry] = &[\n");
    for e in entries {
        let runbook = e
            .runbook
            .as_ref()
            .map_or("None".to_string(), |r| format!("Some({r:?})"));
        let _ = writeln!(
            s,
            "    CatalogEntry {{ code: ErrorCode::{name}, id: {code:?}, http_status: {status}, severity: {sev}, \
             user_message_ja: {ja:?}, user_message_en: {en:?}, user_message_id: {idm:?}, cause: {cause:?}, diagnosis: {diag:?}, fix: {fix:?}, \
             runbook: {runbook}, test: {test:?}, retired: {retired} }},",
            name = e.name,
            code = e.code,
            status = e.http_status,
            sev = severity_variant(&e.severity),
            ja = e.user_message_ja,
            en = e.user_message_en,
            idm = e.user_message_id,
            cause = e.cause,
            diag = e.diagnosis,
            fix = e.fix,
            test = e.test,
            retired = e.retired,
        );
    }
    s.push_str("];\n");
    s
}
