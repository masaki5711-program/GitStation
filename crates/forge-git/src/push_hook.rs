//! The push checks' pre-receive hook (M3 X8, ADR-0008 amendment X8): how
//! `forge serve` arms it for one receive-pack, what the hook
//! (`forge hook pre-receive`) does, and how serve reads what it decided.
//!
//! - **The hook script** — `<git home>/push-hooks/pre-receive`, forge's
//!   own [`HOOK_SCRIPT`] (three lines; mode 0700 on Unix). receive-pack of
//!   a push with checks gets `-c core.hooksPath=<git home>/push-hooks`
//!   instead of the empty hooks directory. A directory or script that is
//!   not exactly forge's refuses the push (`FG-GIT-0001 reason=hooks_dir`,
//!   as the empty directory does).
//! - **One run per push** ([`PushCheckRun`]) — `<git home>/push-checks/<nonce>/`
//!   (0700) holding `policy`, written by serve: the nonce, the request id,
//!   the language, the storage root, the repository id, git's binary and
//!   home, the blob size limit. receive-pack gets `FORGE_PUSH_CHECK_DIR`
//!   (that directory) and `FORGE_PUSH_CHECK_EXE` (the forge binary) in its
//!   cleared environment; the hook inherits them. The hook holds no
//!   secret and connects to no database.
//! - **The hook** ([`run_pre_receive`]) reads the policy and git's update
//!   lines, checks git's quarantine against the repository, runs the scan
//!   ([`crate::push_scan`]) and writes `result` (temporary file, then
//!   rename): the nonce, the verdict, the counts and the findings (rule,
//!   blob, commit, path — never content). It prints the pusher's lines to
//!   stderr (git relays them as `remote: …`) and exits 1 to refuse.
//!   Findings refuse; an internal failure refuses (fail closed,
//!   FG-GIT-0023); a bound hit accepts with a warn line (fail open,
//!   FG-GIT-0024).
//! - **After git exits** serve reads the result ([`PushCheckRun::outcome`]):
//!   none (or another nonce) while refs were applied means the hook did
//!   not run (`FG-GIT-0023 reason=hook_not_run`, an alert) — git skips a
//!   missing or non-executable hook silently, so this check is what makes
//!   a skipped hook visible. Then the run directory is removed.

use std::ffi::{OsStr, OsString};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use forge_core::RepoId;
use forge_errors::{ErrorCode, ForgeError, Lang};

use crate::command::{Git, GitCommand, GitConfig};
use crate::push_scan::{Finding, FindingKind, Quarantine, ScanLimits, ScanReport};
use crate::storage::StorageRoot;
use crate::upload_request::is_object_id;

/// The variable naming the run directory.
pub const DIR_ENV: &str = "FORGE_PUSH_CHECK_DIR";
/// The variable naming the forge binary the hook script runs.
pub const EXE_ENV: &str = "FORGE_PUSH_CHECK_EXE";
/// The pre-receive hook, exactly.
pub const HOOK_SCRIPT: &str = "#!/bin/sh\n\
# forge push checks (M3 X8, ADR-0008). Generated by forge; any change refuses pushes.\n\
exec \"$FORGE_PUSH_CHECK_EXE\" hook pre-receive\n";
/// The hook's file name.
const HOOK_NAME: &str = "pre-receive";
/// The format version of `policy` and `result`.
const VERSION: &str = "1";
/// The most bytes of git's update lines the hook reads (1000 refs fit).
pub const MAX_HOOK_STDIN: usize = 1024 * 1024;
/// The largest file the run reads back (policy, result).
const MAX_RUN_FILE: u64 = 1024 * 1024;
/// Captured git output in the hook (the object list of a large push).
const HOOK_MAX_OUTPUT: usize = 64 * 1024 * 1024;

fn failed(reason: &'static str) -> ForgeError {
    ForgeError::new(ErrorCode::PushCheckFailed).with_context("reason", reason)
}

/// What serve decides for one push.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PushCheckPolicy {
    pub request_id: String,
    pub lang: Lang,
    pub repo_id: RepoId,
    pub max_blob_bytes: u64,
}

/// One armed push (serve's side; see the module docs).
#[derive(Debug)]
pub struct PushCheckRun {
    dir: PathBuf,
    nonce: String,
    exe: OsString,
    hooks: PathBuf,
    /// [`PushCheckRun::remove`] ran (the drop then leaves the directory).
    removed: bool,
}

impl Drop for PushCheckRun {
    /// A run dropped without [`PushCheckRun::remove`] (an error path before
    /// git ran) still removes its directory, best effort: the error that
    /// ended the push is the one logged.
    fn drop(&mut self) {
        if !self.removed {
            let _ = std::fs::remove_dir_all(&self.dir); // ignore: best effort, see above
        }
    }
}

/// The hook's verdict.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    Accepted,
    Refused,
    Failed,
}

impl Verdict {
    fn as_str(self) -> &'static str {
        match self {
            Self::Accepted => "accepted",
            Self::Refused => "refused",
            Self::Failed => "failed",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        match s {
            "accepted" => Some(Self::Accepted),
            "refused" => Some(Self::Refused),
            "failed" => Some(Self::Failed),
            _ => None,
        }
    }
}

/// What the hook wrote.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookOutcome {
    pub verdict: Verdict,
    /// `failed`: the hook's FG-GIT-0023 `reason` (and `detail`, `cause_code`).
    pub reason: Option<String>,
    pub detail: Option<String>,
    pub cause_code: Option<String>,
    pub report: ScanReport,
}

impl Git {
    /// The push hooks directory: `<home>/push-hooks`.
    pub fn push_hooks_dir(&self) -> PathBuf {
        self.config().home.join("push-hooks")
    }

    /// Arm the checks for one push: the hook script in place, a fresh run
    /// directory with the policy. `exe`: the forge binary (`forge hook
    /// pre-receive`).
    pub fn push_check_run(
        &self,
        storage: &StorageRoot,
        exe: &Path,
        policy: &PushCheckPolicy,
    ) -> Result<PushCheckRun, ForgeError> {
        let home = &self.config().home;
        let runs = home.join("push-checks");
        crate::smart_http::ensure_private_dir(&runs).map_err(|e| {
            failed("run_dir")
                .with_context("detail", "create")
                .with_source(e)
        })?;
        let nonce = uuid::Uuid::new_v4().simple().to_string();
        let dir = runs.join(&nonce);
        crate::smart_http::create_private_dir(&dir).map_err(|e| {
            failed("run_dir")
                .with_context("detail", "create")
                .with_source(e)
        })?;
        let hooks = self.push_hooks_dir();
        ensure_hook(&hooks, &dir)?;
        let Some(exe) = exe.to_str().filter(|_| exe.is_absolute()) else {
            return Err(failed("run_dir").with_context("detail", "exe_not_absolute_utf8"));
        };
        // git for Windows runs the hook with its sh: forward slashes.
        let exe = if cfg!(windows) {
            exe.replace('\\', "/")
        } else {
            exe.to_owned()
        };
        let mut text = String::new();
        let mut put = |k: &str, v: &str| {
            let _ = writeln!(text, "{k}\t{}", one_line(v)); // ignore: writing to a String cannot fail
        };
        put("version", VERSION);
        put("nonce", &nonce);
        put("request_id", &policy.request_id);
        put("lang", policy.lang.as_str());
        put("storage_root", &storage.path().to_string_lossy());
        put("repo_id", &policy.repo_id.get().to_string());
        put("git_bin", &self.config().bin.to_string_lossy());
        put("git_home", &home.to_string_lossy());
        put("max_blob_bytes", &policy.max_blob_bytes.to_string());
        write_private(&dir.join("policy"), text.as_bytes()).map_err(|e| {
            failed("run_dir")
                .with_context("detail", "policy_write")
                .with_source(e)
        })?;
        Ok(PushCheckRun {
            dir,
            nonce,
            exe: OsString::from(exe),
            hooks,
            removed: false,
        })
    }
}

impl GitCommand {
    /// receive-pack with the push checks: `core.hooksPath` is the push
    /// hooks directory, and the hook's two variables are set.
    #[must_use]
    pub fn with_push_checks(self, run: &PushCheckRun) -> Self {
        self.replace_config("core.hooksPath", run.hooks.as_os_str())
            .env(DIR_ENV, run.dir.clone().into_os_string())
            .env(EXE_ENV, run.exe.clone()) // clone: the run keeps its own
    }
}

impl PushCheckRun {
    /// The run directory (tests, logs).
    pub fn dir(&self) -> &Path {
        &self.dir
    }

    /// What this push's hook wrote: `None` when it wrote nothing.
    /// A result of another run (nonce) or one forge cannot read is
    /// `FG-GIT-0023 reason=result_invalid`.
    pub fn outcome(&self) -> Result<Option<HookOutcome>, ForgeError> {
        let path = self.dir.join("result");
        let text = match read_small(&path) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(failed("result_invalid").with_source(e)),
        };
        let outcome = parse_result(&text)?;
        if outcome.0 != self.nonce {
            return Err(failed("result_invalid").with_context("detail", "nonce_mismatch"));
        }
        Ok(Some(outcome.1))
    }

    /// Remove the run directory.
    pub fn remove(mut self) -> Result<(), ForgeError> {
        self.removed = true;
        std::fs::remove_dir_all(&self.dir).map_err(|e| {
            failed("run_dir")
                .with_context("detail", "remove")
                .with_source(e)
        })
    }
}

/// The hook script in place: the directory a real directory holding
/// exactly [`HOOK_SCRIPT`] as `pre-receive` (written when missing, through
/// a temporary file in `scratch` and a rename).
fn ensure_hook(hooks: &Path, scratch: &Path) -> Result<(), ForgeError> {
    let bad = |detail: &'static str| {
        ForgeError::new(ErrorCode::GitUnavailable)
            .with_context("reason", "hooks_dir")
            .with_context("detail", detail)
            .with_context("path", hooks.display())
    };
    crate::smart_http::ensure_private_dir(hooks)
        .map_err(|e| bad("create_failed").with_source(e))?;
    let meta = std::fs::symlink_metadata(hooks).map_err(|e| bad("unreadable").with_source(e))?;
    if !meta.is_dir() {
        return Err(bad("not_a_directory"));
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        if meta.permissions().mode() & 0o022 != 0 {
            return Err(bad("insecure_permissions"));
        }
    }
    let script = hooks.join(HOOK_NAME);
    for entry in std::fs::read_dir(hooks).map_err(|e| bad("unreadable").with_source(e))? {
        let entry = entry.map_err(|e| bad("unreadable").with_source(e))?;
        if entry.file_name() != OsStr::new(HOOK_NAME) {
            return Err(bad("unexpected_entry"));
        }
    }
    match std::fs::symlink_metadata(&script) {
        Ok(m) if m.is_file() => {
            let text = read_small(&script).map_err(|e| bad("unreadable").with_source(e))?;
            if text != HOOK_SCRIPT {
                return Err(bad("push_hook_mismatch"));
            }
            Ok(())
        }
        Ok(_) => Err(bad("push_hook_mismatch")),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            let tmp = scratch.join("pre-receive.tmp");
            write_private(&tmp, HOOK_SCRIPT.as_bytes())
                .map_err(|e| bad("create_failed").with_source(e))?;
            std::fs::rename(&tmp, &script).map_err(|e| bad("create_failed").with_source(e))
        }
        Err(e) => Err(bad("unreadable").with_source(e)),
    }
}

/// Write a new file readable (and, for the hook, runnable) by the owner
/// only.
fn write_private(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write as _;
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(0o700);
    }
    let mut file = options.open(path)?;
    file.write_all(bytes)?;
    file.sync_all()
}

fn read_small(path: &Path) -> std::io::Result<String> {
    use std::io::Read as _;
    let file = std::fs::File::open(path)?;
    let mut text = String::new();
    file.take(MAX_RUN_FILE).read_to_string(&mut text)?;
    Ok(text)
}

/// A value on one line of a run file (tabs and newlines replaced).
fn one_line(v: &str) -> String {
    v.replace(['\t', '\n', '\r'], " ")
}

/// `key\tvalue` lines (a `finding` line has more fields).
fn fields(text: &str) -> impl Iterator<Item = (&str, &str)> {
    text.lines().filter_map(|l| l.split_once('\t'))
}

/// The hook's inputs from its environment.
#[derive(Debug, Clone, Default)]
pub struct HookEnv {
    /// `FORGE_PUSH_CHECK_DIR`.
    pub dir: Option<OsString>,
    /// git's `GIT_OBJECT_DIRECTORY` / `GIT_ALTERNATE_OBJECT_DIRECTORIES`.
    pub object_dir: Option<OsString>,
    pub alternates: Option<OsString>,
}

/// What the hook process does: its stderr (relayed to the pusher) and
/// whether git may go on.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookExit {
    pub accept: bool,
    pub stderr: String,
}

/// The policy as the hook reads it.
struct ReadPolicy {
    nonce: String,
    request_id: String,
    lang: Lang,
    storage_root: PathBuf,
    repo_id: RepoId,
    git_bin: PathBuf,
    git_home: PathBuf,
    max_blob_bytes: u64,
}

fn read_policy(dir: &Path) -> Result<ReadPolicy, ForgeError> {
    let text =
        read_small(&dir.join("policy")).map_err(|e| failed("policy_unreadable").with_source(e))?;
    let get = |key: &'static str| {
        fields(&text)
            .find(|(k, _)| *k == key)
            .map(|(_, v)| v.to_owned())
            .ok_or_else(|| failed("policy_invalid").with_context("detail", key))
    };
    let invalid = |key: &'static str| failed("policy_invalid").with_context("detail", key);
    if get("version")? != VERSION {
        return Err(invalid("version"));
    }
    let nonce = get("nonce")?;
    if nonce.len() != 32 || !nonce.bytes().all(|b| b.is_ascii_hexdigit()) {
        return Err(invalid("nonce"));
    }
    Ok(ReadPolicy {
        nonce,
        request_id: get("request_id")?,
        lang: Lang::parse(&get("lang")?).ok_or_else(|| invalid("lang"))?,
        storage_root: PathBuf::from(get("storage_root")?),
        repo_id: RepoId::new(get("repo_id")?.parse().map_err(|_| invalid("repo_id"))?),
        git_bin: PathBuf::from(get("git_bin")?),
        git_home: PathBuf::from(get("git_home")?),
        max_blob_bytes: get("max_blob_bytes")?
            .parse()
            .map_err(|_| invalid("max_blob_bytes"))?,
    })
}

/// The new tips of git's update lines (`<old> <new> <ref>`; deletes left
/// out).
fn tips(stdin: &[u8]) -> Result<Vec<String>, ForgeError> {
    let invalid = || failed("stdin_invalid");
    if stdin.len() > MAX_HOOK_STDIN {
        return Err(invalid().with_context("detail", "too_long"));
    }
    let text = std::str::from_utf8(stdin).map_err(|_| invalid().with_context("detail", "utf8"))?;
    let mut tips = Vec::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        let mut parts = line.splitn(3, ' ');
        let (Some(old), Some(new), Some(_)) = (parts.next(), parts.next(), parts.next()) else {
            return Err(invalid().with_context("detail", "line"));
        };
        if !is_object_id(old) || !is_object_id(new) {
            return Err(invalid().with_context("detail", "object_id"));
        }
        if !new.bytes().all(|b| b == b'0') && !tips.iter().any(|t| t == new) {
            tips.push(new.to_owned());
        }
    }
    Ok(tips)
}

/// The hook (see the module docs). Never panics; every way out is an
/// exit decision with the pusher's lines.
pub async fn run_pre_receive(env: HookEnv, stdin: &[u8]) -> HookExit {
    let Some(dir) = env
        .dir
        .as_ref()
        .map(PathBuf::from)
        .filter(|d| d.is_absolute())
    else {
        return refuse_failed(Lang::En, None, &failed("env_missing"));
    };
    let policy = match read_policy(&dir) {
        Ok(p) => p,
        Err(e) => {
            // No nonce to sign a result with: serve sees `hook_no_result`.
            return refuse_failed(Lang::En, None, &e);
        }
    };
    let (outcome, exit) = match check(&policy, &env, stdin).await {
        Ok(report) => decide(&policy, report),
        Err(e) => {
            let exit = refuse_failed(policy.lang, Some(&policy.request_id), &e);
            (failed_outcome(&e), exit)
        }
    };
    match write_result(&dir, &policy.nonce, &outcome) {
        Ok(()) => exit,
        Err(e) => refuse_failed(policy.lang, Some(&policy.request_id), &e),
    }
}

async fn check(policy: &ReadPolicy, env: &HookEnv, stdin: &[u8]) -> Result<ScanReport, ForgeError> {
    let tips = tips(stdin)?;
    let storage = StorageRoot::open(&policy.storage_root).map_err(|e| {
        failed("storage")
            .with_context("cause_code", e.code().id())
            .with_source(e)
    })?;
    let repo = storage.existing(policy.repo_id).map_err(|e| {
        failed("storage")
            .with_context("cause_code", e.code().id())
            .with_source(e)
    })?;
    let quarantine =
        Quarantine::from_hook_env(&repo, env.object_dir.as_deref(), env.alternates.as_deref())?;
    let mut cfg = GitConfig::new(&policy.git_bin, &policy.git_home);
    cfg.max_output_bytes = HOOK_MAX_OUTPUT;
    cfg.max_concurrency = 2;
    let git = Git::new(cfg);
    git.scan_push(
        &repo,
        quarantine.as_ref(),
        &tips,
        &ScanLimits::new(policy.max_blob_bytes),
    )
    .await
}

fn failed_outcome(e: &ForgeError) -> HookOutcome {
    let ctx = |key: &str| {
        e.context()
            .iter()
            .find(|(k, _)| *k == key)
            .map(|(_, v)| v.clone()) // clone: the outcome owns its copy
    };
    HookOutcome {
        verdict: Verdict::Failed,
        reason: ctx("reason").or_else(|| Some("internal".to_owned())),
        detail: ctx("detail").or_else(|| ctx("subcommand")),
        cause_code: ctx("cause_code"),
        report: ScanReport::default(),
    }
}

/// Findings refuse; otherwise accept (with a warn line when incomplete).
fn decide(policy: &ReadPolicy, report: ScanReport) -> (HookOutcome, HookExit) {
    let lang = policy.lang;
    let mut stderr = String::new();
    let accept = report.findings.is_empty();
    if accept {
        if report.incomplete.is_some() {
            let code = ErrorCode::PushCheckIncomplete;
            let _ = writeln!(stderr, "{} {}", code.id(), code.user_message(lang));
            // ignore: String
        }
    } else {
        let mut codes: Vec<ErrorCode> = Vec::new();
        for f in &report.findings {
            if !codes.contains(&f.kind.code()) {
                codes.push(f.kind.code());
            }
        }
        for code in codes {
            let _ = writeln!(stderr, "{} {}", code.id(), code.user_message(lang)); // ignore: String
            for f in report.findings.iter().filter(|f| f.kind.code() == code) {
                let _ = writeln!(stderr, "  {}", finding_line(f, policy.max_blob_bytes));
                // ignore: String
            }
        }
        let more = report.total_findings.saturating_sub(report.findings.len());
        if more > 0 {
            let _ = writeln!(stderr, "  … and {more} more"); // ignore: String
        }
        let _ = writeln!(stderr, "(request_id: {})", policy.request_id); // ignore: String
    }
    let verdict = if accept {
        Verdict::Accepted
    } else {
        Verdict::Refused
    };
    (
        HookOutcome {
            verdict,
            reason: None,
            detail: None,
            cause_code: None,
            report,
        },
        HookExit { accept, stderr },
    )
}

/// One finding for the pusher: rule, path, commit — never content.
pub fn finding_line(f: &Finding, limit: u64) -> String {
    let path = if f.path.is_empty() {
        format!("blob {}", short(&f.blob))
    } else {
        f.path.clone() // clone: formatted below
    };
    let commit = f
        .commit
        .as_deref()
        .map(|c| format!(" (commit {})", short(c)))
        .unwrap_or_default();
    match &f.kind {
        FindingKind::LargeBlob { size } => {
            format!("{path}{commit}: {size} bytes, over the limit of {limit} bytes")
        }
        FindingKind::Secret { rule } => format!("{path}{commit}: looks like a secret ({rule})"),
    }
}

fn short(id: &str) -> &str {
    id.get(..12).unwrap_or(id)
}

fn refuse_failed(lang: Lang, request_id: Option<&str>, e: &ForgeError) -> HookExit {
    let code = ErrorCode::PushCheckFailed;
    let id = request_id.unwrap_or("-");
    let reason = e
        .context()
        .iter()
        .find(|(k, _)| *k == "reason")
        .map_or("internal", |(_, v)| v.as_str());
    HookExit {
        accept: false,
        stderr: format!(
            "{} {} (request_id: {id}, reason: {reason})\n",
            code.id(),
            code.user_message(lang)
        ),
    }
}

fn write_result(dir: &Path, nonce: &str, o: &HookOutcome) -> Result<(), ForgeError> {
    let mut text = String::new();
    let r = &o.report;
    let opt = |v: &Option<String>| v.as_deref().map(one_line).unwrap_or_else(|| "-".to_owned());
    let _ = write!(
        text,
        "version\t{VERSION}\nnonce\t{nonce}\nverdict\t{}\nreason\t{}\ndetail\t{}\ncause_code\t{}\n\
         incomplete\t{}\nobjects\t{}\nblobs_scanned\t{}\nbytes_scanned\t{}\nallowed\t{}\ntotal_findings\t{}\n",
        o.verdict.as_str(),
        opt(&o.reason),
        opt(&o.detail),
        opt(&o.cause_code),
        r.incomplete.unwrap_or("-"),
        r.objects,
        r.blobs_scanned,
        r.bytes_scanned,
        r.allowed,
        r.total_findings,
    ); // ignore: writing to a String cannot fail
    for f in &r.findings {
        let (kind, detail) = match &f.kind {
            FindingKind::LargeBlob { size } => ("large_blob", size.to_string()),
            FindingKind::Secret { rule } => ("secret", one_line(rule)),
        };
        let _ = writeln!(
            text,
            "finding\t{kind}\t{detail}\t{}\t{}\t{}",
            f.blob,
            f.commit.as_deref().unwrap_or("-"),
            one_line(&f.path)
        ); // ignore: as above
    }
    let tmp = dir.join("result.tmp");
    write_private(&tmp, text.as_bytes())
        .and_then(|()| std::fs::rename(&tmp, dir.join("result")))
        .map_err(|e| failed("result_write").with_source(e))
}

/// The nonce and the outcome of a result file.
fn parse_result(text: &str) -> Result<(String, HookOutcome), ForgeError> {
    let invalid = |detail: &'static str| failed("result_invalid").with_context("detail", detail);
    let get = |key: &'static str| {
        fields(text)
            .find(|(k, _)| *k == key)
            .map(|(_, v)| v)
            .ok_or_else(|| invalid(key))
    };
    let opt = |key: &'static str| -> Result<Option<String>, ForgeError> {
        let v = get(key)?;
        Ok((v != "-").then(|| v.to_owned()))
    };
    let num = |key: &'static str| -> Result<u64, ForgeError> {
        get(key)?.parse().map_err(|_| invalid(key))
    };
    let count = |key: &'static str| -> Result<usize, ForgeError> {
        usize::try_from(num(key)?).map_err(|_| invalid(key))
    };
    if get("version")? != VERSION {
        return Err(invalid("version"));
    }
    let incomplete = match get("incomplete")? {
        "-" => None,
        "objects_cap" => Some("objects_cap"),
        "bytes_cap" => Some("bytes_cap"),
        "deadline" => Some("deadline"),
        _ => return Err(invalid("incomplete")),
    };
    let mut findings = Vec::new();
    for line in text.lines() {
        let Some(rest) = line.strip_prefix("finding\t") else {
            continue;
        };
        let mut p = rest.splitn(5, '\t');
        let (Some(kind), Some(detail), Some(blob), Some(commit), Some(path)) =
            (p.next(), p.next(), p.next(), p.next(), p.next())
        else {
            return Err(invalid("finding"));
        };
        let kind = match kind {
            "large_blob" => FindingKind::LargeBlob {
                size: detail.parse().map_err(|_| invalid("finding"))?,
            },
            "secret" => FindingKind::Secret {
                rule: detail.to_owned(),
            },
            _ => return Err(invalid("finding")),
        };
        if !is_object_id(blob) || (commit != "-" && !is_object_id(commit)) {
            return Err(invalid("finding"));
        }
        findings.push(Finding {
            kind,
            blob: blob.to_owned(),
            path: path.to_owned(),
            commit: (commit != "-").then(|| commit.to_owned()),
        });
    }
    let outcome = HookOutcome {
        verdict: Verdict::parse(get("verdict")?).ok_or_else(|| invalid("verdict"))?,
        reason: opt("reason")?,
        detail: opt("detail")?,
        cause_code: opt("cause_code")?,
        report: ScanReport {
            findings,
            total_findings: count("total_findings")?,
            objects: count("objects")?,
            blobs_scanned: count("blobs_scanned")?,
            bytes_scanned: num("bytes_scanned")?,
            allowed: count("allowed")?,
            incomplete,
        },
    };
    Ok((get("nonce")?.to_owned(), outcome))
}

