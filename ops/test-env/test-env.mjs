#!/usr/bin/env node
// M3 test environment driver (plan 11 §7 / P5). Node built-ins only.
//
//   node ops/test-env/test-env.mjs up       # secrets, containers, DB, Keycloak realm, forge serve + worker
//   node ops/test-env/test-env.mjs status   # ports, containers, processes, readiness
//   node ops/test-env/test-env.mjs down     # stop forge, remove ONLY the gs-m3-test containers (keeps data)
//   node ops/test-env/test-env.mjs reset    # down + delete the gs-m3-test volumes and ops/test-env/.local
//
// Runbook: ops/runbooks/m3-test-environment.md. Everything binds 127.0.0.1;
// data is synthetic; secrets live in ops/test-env/.local (gitignored).
import { spawn, spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const local = join(here, '.local');
const PROJECT = 'gs-m3-test';
const P = { gitstation: 28080, gsPg: 25432, keycloak: 28180, smtp: 28025, mailUi: 28026 };
const REALM = 'forge-m3-test';
const forgeExe = process.env.FORGE_BIN ?? join(root, 'target', 'release', process.platform === 'win32' ? 'forge.exe' : 'forge');
const f = (name) => join(local, name);
const hex = (n) => randomBytes(n).toString('hex');

/** Replace every generated secret value with *** (psql echoes statements, and these hold passwords). */
function redact(text) {
  let out = text;
  try {
    const values = [];
    for (const n of ['db-app.pw', 'db-migrate.pw', 'oidc-client-secret']) values.push(readFileSync(f(n), 'utf8').trim());
    for (const l of readFileSync(f('compose.env'), 'utf8').split(String.fromCharCode(10))) values.push(l.slice(l.indexOf('=') + 1).trim());
    for (const v of values) if (v.length >= 8) out = out.split(v).join('***');
  } catch { /* no secrets generated yet */ }
  return out;
}

function run(cmd, args, opts = {}) {
  let r = spawnSync(cmd, args, { encoding: 'utf8', ...opts });
  // The Docker backend of a busy shared host sometimes times out dialing once.
  for (let i = 0; i < 2 && cmd === 'docker' && r.status !== 0 && /timed out dialing|failed to connect to the backend/.test(r.stderr ?? ''); i++) {
    r = spawnSync(cmd, args, { encoding: 'utf8', ...opts });
  }
  if (r.status !== 0 && !opts.allowFail) {
    throw new Error(redact(`${cmd} ${args.join(' ')} failed (${r.status})\n${r.stdout ?? ''}${r.stderr ?? ''}`));
  }
  return r;
}
const compose = (...args) =>
  run('docker', ['compose', '-p', PROJECT, '-f', join(here, 'compose.yml'), '--env-file', f('compose.env'), ...args], { cwd: here });

function portBusy(port) {
  // Refuse to start on top of a port someone else holds (shared host).
  const r = spawnSync(process.platform === 'win32' ? 'netstat' : 'ss', process.platform === 'win32' ? ['-ano'] : ['-ltn'], { encoding: 'utf8' });
  return new RegExp(`[:.]${port}\\s`).test(r.stdout ?? '');
}

function init() {
  if (existsSync(f('compose.env'))) return;
  mkdirSync(local, { recursive: true });
  const s = { gsSuper: hex(16), kcPg: hex(16), kcAdmin: hex(16), gitstation: hex(24), kanflow: hex(24), app: hex(16), migrate: hex(16) };
  writeFileSync(f('compose.env'), [
    `GS_PG_SUPERUSER_PASSWORD=${s.gsSuper}`, `KC_PG_PASSWORD=${s.kcPg}`, `KC_ADMIN_PASSWORD=${s.kcAdmin}`,
    `GITSTATION_CLIENT_SECRET=${s.gitstation}`, `KANFLOW_TEST_CLIENT_SECRET=${s.kanflow}`, ''].join('\n'), { mode: 0o600 });
  const secret = (name, v) => writeFileSync(f(name), `${v}\n`, { mode: 0o600 });
  secret('db-app.pw', s.app);
  secret('db-migrate.pw', s.migrate);
  secret('oidc-client-secret', s.gitstation);
  secret('cursor-keys', `1 ${hex(32)}`);
  secret('audit-seal-keys', `1 ${hex(32)}`);
  secret('web-session-keys', `1 ${hex(32)}`);
  const q = (p) => JSON.stringify(p.replaceAll(String.fromCharCode(92), '/'));
  const common = `[database]
url = "postgres://forge_app@127.0.0.1:${P.gsPg}/forge"
password_file = ${q(f('db-app.pw'))}
tls_mode = "disable"
`;
  writeFileSync(f('forge.toml'), `# generated by test-env.mjs; synthetic test environment
[server]
bind = "127.0.0.1:${P.gitstation}"
[storage]
root = ${q(f('storage'))}
${common}
[api]
cursor_keys_file = ${q(f('cursor-keys'))}
[audit]
seal_keys_file = ${q(f('audit-seal-keys'))}
[web]
base_url = "http://127.0.0.1:${P.gitstation}"
session_key_file = ${q(f('web-session-keys'))}
[auth.oidc]
issuer = "http://127.0.0.1:${P.keycloak}/realms/${REALM}"
client_id = "gitstation"
client_secret_file = ${q(f('oidc-client-secret'))}
`);
  writeFileSync(f('forge-migrate.toml'), `[database]
url = "postgres://forge_app@127.0.0.1:${P.gsPg}/forge"
password_file = ${q(f('db-app.pw'))}
migrate_url = "postgres://forge_migrator@127.0.0.1:${P.gsPg}/forge"
migrate_password_file = ${q(f('db-migrate.pw'))}
tls_mode = "disable"
`);
  mkdirSync(f('storage'), { recursive: true });
  if (process.platform === 'win32' && process.env.USERNAME) {
    // Only the current user (and nobody inherited) may read the generated secrets.
    run('icacls', [local, '/inheritance:r', '/grant:r', `${process.env.USERNAME}:(OI)(CI)F`], { allowFail: true });
  }
}

function psqlSuper(args, input) {
  return run('docker', ['compose', '-p', PROJECT, '-f', join(here, 'compose.yml'), '--env-file', f('compose.env'),
    'exec', '-T', 'gs-test-pg', 'psql', '-U', 'postgres', '-v', 'ON_ERROR_STOP=1', ...args], { cwd: here, input });
}

function bootstrapDb() {
  const dir = join(root, 'ops', 'db', 'bootstrap');
  const has = psqlSuper(['-d', 'postgres', '-tAc', "SELECT 1 FROM pg_database WHERE datname='forge'"]).stdout.trim() === '1';
  psqlSuper(['-d', 'postgres', '-f', '-'], readFileSync(join(dir, '01-cluster-roles.sql')));
  const pw = (n) => readFileSync(f(n), 'utf8').trim();
  psqlSuper(['-d', 'postgres'], `ALTER ROLE forge_app PASSWORD '${pw('db-app.pw')}';\nALTER ROLE forge_migrator PASSWORD '${pw('db-migrate.pw')}';\n`);
  if (!has) psqlSuper(['-d', 'postgres', '-v', 'dbname=forge', '-f', '-'], readFileSync(join(dir, '02-create-database.sql')));
  psqlSuper(['-d', 'forge', '-f', '-'], readFileSync(join(dir, '03-database-objects.sql')));
}

async function waitFor(url, label, ms = 240000) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try { if ((await fetch(url, { signal: AbortSignal.timeout(3000) })).ok) return; } catch { /* retry */ }
    await new Promise((r) => setTimeout(r, 2000));
  }
  throw new Error(`${label} did not become ready: ${url}`);
}

const pidFile = (n) => f(`${n}.pid`);
/** Is this PID really OUR forge (this worktree's binary, our config)? A reused PID on a shared host must never be killed. */
function isOurForge(pid) {
  if (!Number.isInteger(pid) || pid <= 0) return false;
  let exe = '';
  let cmdline = '';
  if (process.platform === 'win32') {
    const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command',
      `$p = Get-CimInstance Win32_Process -Filter "ProcessId=${pid}"; if ($p) { $p.ExecutablePath; $p.CommandLine }`], { encoding: 'utf8' });
    [exe = '', cmdline = ''] = (r.stdout ?? '').split(/\r?\n/);
  } else {
    const r = spawnSync('ps', ['-o', 'args=', '-p', String(pid)], { encoding: 'utf8' });
    cmdline = (r.stdout ?? '').trim();
    exe = cmdline.split(' ')[0];
  }
  const norm = (x) => x.replaceAll(String.fromCharCode(92), '/').toLowerCase();
  return norm(exe) === norm(forgeExe) && norm(cmdline).includes(norm(f('forge.toml')));
}
const alive = isOurForge;
function startForge(name, sub) {
  if (existsSync(pidFile(name)) && alive(Number(readFileSync(pidFile(name), 'utf8')))) return;
  const log = openSync(f(`${name}.log`), 'a');
  const child = spawn(forgeExe, ['--config', f('forge.toml'), sub], { detached: true, stdio: ['ignore', log, log], windowsHide: true });
  child.unref();
  writeFileSync(pidFile(name), String(child.pid));
}
function stopForge(name) {
  if (!existsSync(pidFile(name))) return;
  const pid = Number(readFileSync(pidFile(name), 'utf8'));
  if (isOurForge(pid)) process.kill(pid);
  else console.error(`test-env: pid ${pid} (${name}) is not this environment's forge; stale pid file removed, nothing killed`);
  rmSync(pidFile(name), { force: true });
}

async function up() {
  if (!existsSync(forgeExe)) throw new Error('forge binary not found: ' + forgeExe + ' (cargo build --release -p forge-cli --features embed-ui)');
  init();
  const mine = run('docker', ['ps', '--filter', `label=com.docker.compose.project=${PROJECT}`, '--format', '{{.Names}}']).stdout.trim();
  if (!mine) {
    const busy = Object.entries(P).filter(([k, p]) => k !== 'gitstation' && portBusy(p));
    if (busy.length) throw new Error('port(s) already in use, not starting: ' + busy.map((b) => b.join('=')).join(', '));
  }
  compose('up', '-d', '--wait', 'gs-test-pg', 'kc-test-pg', 'mailpit');
  compose('up', '-d', 'keycloak');
  bootstrapDb();
  run(forgeExe, ['--config', f('forge-migrate.toml'), 'db', 'migrate'], { stdio: 'inherit' });
  await waitFor(`http://127.0.0.1:${P.keycloak}/realms/${REALM}/.well-known/openid-configuration`, 'Keycloak');
  if (portBusy(P.gitstation) && !existsSync(pidFile('serve'))) throw new Error(`port ${P.gitstation} is in use by another process`);
  startForge('serve', 'serve');
  startForge('worker', 'worker');
  await waitFor(`http://127.0.0.1:${P.gitstation}/readyz`, 'GitStation');
  writeFileSync(f('journey.env.json'), JSON.stringify({
    gitstation: `http://127.0.0.1:${P.gitstation}`, keycloak: `http://127.0.0.1:${P.keycloak}`, realm: REALM,
    adminUser: 'synthetic-admin', adminPassword: readFileSync(f('compose.env'), 'utf8').match(/KC_ADMIN_PASSWORD=(.*)/)[1],
    composeProject: PROJECT, composeFile: join(here, 'compose.yml'), composeEnv: f('compose.env'),
  }, null, 2), { mode: 0o600 });
  console.log(status());
  console.log(`\nJourney: GS_M3_TESTENV=${f('journey.env.json').replaceAll('\\', '/')} npm --prefix web run journey:keycloak`);
}

function status() {
  const rows = [['gitstation', P.gitstation], ['gs-test-pg', P.gsPg], ['keycloak', P.keycloak], ['mailpit smtp', P.smtp], ['mailpit ui', P.mailUi]]
    .map(([n, p]) => `${n.padEnd(14)} 127.0.0.1:${p}  ${portBusy(p) ? 'listening' : 'closed'}`);
  const ps = existsSync(f('compose.env')) ? compose('ps', '--format', 'table {{.Service}}\t{{.Status}}', '-a').stdout : '(not initialised)';
  const procs = ['serve', 'worker'].map((n) => `forge ${n}: ${existsSync(pidFile(n)) && alive(Number(readFileSync(pidFile(n), 'utf8'))) ? 'running' : 'stopped'}`);
  return [...rows, '', ps, ...procs].join('\n');
}

function down(volumes) {
  stopForge('serve');
  stopForge('worker');
  if (existsSync(f('compose.env'))) compose('down', ...(volumes ? ['-v'] : []));
  if (volumes) rmSync(local, { recursive: true, force: true });
}

const cmd = process.argv[2];
try {
  if (cmd === 'up') await up();
  else if (cmd === 'status') console.log(status());
  else if (cmd === 'down') down(false);
  else if (cmd === 'reset') down(true);
  else {
    console.error('usage: test-env.mjs up|status|down|reset');
    process.exit(2);
  }
} catch (e) {
  console.error(String(e.message ?? e));
  process.exit(1);
}
